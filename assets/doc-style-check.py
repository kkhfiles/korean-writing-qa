# **보조사(JX)**인지가 그렇다 — 「보내는 때」는 지적이고 「이제는 때가 됐다」는
# 정상인데 글자는 같다. 형태소 분석기는 tag 로 그것을 가른다.
#
#   보내는 때 → 보내/VV + 는/ETM + 때/NNG   → 지적
#   이제는 때 → 이제/NNG + 는/JX  + 때/NNG   → 통과
#   필요할 때 → 하/XSA + ᆯ/ETM  + 때/NNG   → 통과 (ETM 이지만 형태가 「는」이 아니다)
#
