#: 코드펜스 여는 줄 — 백틱이나 물결표 **셋 이상**. CommonMark 가 그렇게 정한다.
#   ⛔ 「백틱 셋」으로 고정하면 **네 겹 펜스가 안 닫힌다.** README 양식처럼 안에
#      세 겹 블록을 담으려면 바깥을 네 겹으로 여는데(GitHub·CommonMark 정상),
#      그때 안쪽 세 겹이 바깥을 닫아 버려 코드가 본문으로 새어 나온다.
FENCE = re.compile(r'^\s*(`{3,}|~{3,})')


def fenced_lines(lines):
    """코드펜스 **안**에 있는 줄 번호(0부터)를 낸다.

    닫는 표시는 **여는 것과 같은 문자로 그 개수 이상**이어야 한다 — 그래야 네 겹
    안의 세 겹이 바깥을 안 닫는다. 여는 줄과 닫는 줄 자체도 안쪽으로 친다.

    ⛔ 이 판정을 부르는 곳마다 따로 적지 않는다. 예전에는 「출처 없는 인용 블록」
       검사가 원문을 그대로 훑어 **펜스를 아예 안 봤고**, 코드 예시 안의
       `> [!NOTE]` 가 문서 본문으로 잡혔다(2026-09-16 실측 · 세 겹에서도 났다).
    """
    inside, opener = set(), None
    for i, line in enumerate(lines):
        m = FENCE.match(line)
        if opener is None:
            if m:
                opener = m.group(1)
                inside.add(i)
            continue
        inside.add(i)
        if m and m.group(1)[0] == opener[0] and len(m.group(1)) >= len(opener):
            opener = None
    return inside


#: 펜스 앞줄이 「예:」류이면 그 블록은 **본보기**다 — 배포되는 글이 아니다.
FENCE_EXAMPLE_LEAD = re.compile(r'예\s*[:：]|예시|보기|❌|✅|나쁜|잘못|금지|고치기 전')
#: 글 갈래 표시 — 비었거나 글을 담는 것. `python`·`bash` 는 코드다.
FENCE_PROSE_TAGS = {'', 'markdown', 'md', 'text', 'txt', 'plaintext'}
#: 배포되는 문장으로 볼 만한 끝맺음. 금지어 목록 같은 **조각 나열**을 빼려고 종결을 본다.
FENCE_SENTENCE = re.compile(r'(?:니다|니까|세요|나요|가요|[다요]\.)\s*$')
FENCE_OPEN = re.compile(r'^(?P<f>`{3,}|~{3,})\s*([A-Za-z0-9_+-]*)\s*$')


def fenced_prose(lines):
    """코드펜스 안에 든 **배포되는 한글 문구**의 줄 수를 낸다.

    **왜 세나.** 공지문 초안·설문 문항·양식이 코드펜스 안에 들어가면 검사에서
    통째로 빠진다. 실제로 공지문의 의문문 소제목(「■ 무엇을 보나」)이 그렇게
    빠져나가 사람이 읽고서야 걸렸다(2026-09-16 DevRel 제안서 세션 §B-1).

    ⛔ **지적하지 않고 세기만 한다.** 펜스 안을 본문처럼 검사하면 바깥 문서의
       개조식 규약이 공지문에 걸린다 — 공지문은 산문이 정상이다. 형식이 문서마다
       하나뿐이라 안쪽만 따로 두는 길이 없다. 그래서 **넘길 곳을 알리는 쪽**으로
       한다(전역 규칙 「자동 판정이 어려우면 넘길 곳을 명시」).

    **실측** — 실문서 644개에서 이 조건에 드는 블록이 9개다. 검사에 넣어 보니
    11건이 나왔고 8건이 실제 배포 문서(공지문 초안·README 양식)에서 왔다.
    """
    total, opener, tag, body, lead = 0, None, '', [], ''
    for line in lines:
        m = FENCE_OPEN.match(line)
        if opener is None:
            if m:
                opener, tag, body = m.group('f'), (m.group(2) or '').lower(), []
            elif line.strip():
                lead = line.strip()
            continue
        if m and m.group('f')[0] == opener[0] and len(m.group('f')) >= len(opener):
            if tag in FENCE_PROSE_TAGS and not FENCE_EXAMPLE_LEAD.search(lead):
                sents = [b for b in body
                         if len(re.findall(r'[가-힣]', b)) >= 6
                         and FENCE_SENTENCE.search(b)]
                if len(sents) >= 3:
                    total += len(sents)
            opener = None
            continue
        body.append(line.strip())
    return total


PRE_CODE = re.compile(r'<pre[^>]*>\s*<code(?P<attrs>[^>]*)>(?P<inner>.*?)</code>\s*</pre>',
                      re.S | re.I)


def pre_code_prose(body):
    """HTML `<pre><code>` 안의 배포 문구 줄 수 — 마크다운 `fenced_prose` 와 같은 기준.

    ⛔ 예전에는 `<pre><code>` 를 먼저 지워서 이 안내가 HTML 에서 안 나왔다 — 같은 안내
       세 줄을 두 형식에 넣으면 마크다운만 알렸다(외부 검토 2026-09-18 · 형식 짝 시험의
       「형식에 따라 갈리는 갈래」로 적혀 있던 것). 블록을 펜스 줄로 되살려 같은 함수에
       넘긴다 — 기준을 두 벌로 두면 한쪽이 낡는다. 앞 글은 블록 바로 앞 글자로 본다
       (「예시」·「❌」 같은 머리가 있으면 보기라 안 센다).
    """
    import html as _html
    lines = []
    for m in PRE_CODE.finditer(body):
        lang = re.search(r'(?:language|lang)-([A-Za-z0-9_+-]+)', m.group('attrs') or '')
        before = [l for l in strip(body[max(0, m.start() - 600):m.start()]).split('\n')
                  if l.strip()]
        inner = _html.unescape(re.sub(r'<[^>]+>', '', m.group('inner')))
        lines += [before[-1] if before else '', '```' + (lang.group(1) if lang else ''),
                  *inner.split('\n'), '```']
    return fenced_prose(lines)


def md_body(raw):
    """(행번호, 원문) — frontmatter·코드펜스 제외. frontmatter는 메타데이터지 본문이 아니다."""
    lines = raw.split('\n')
    start = 0
    if lines and lines[0].strip() == '---':
        for j in range(1, min(len(lines), 60)):
            if lines[j].strip() == '---':
                start = j + 1
                break
    inside = fenced_lines(lines)
    return [(n + 1, lines[n]) for n in range(start, len(lines)) if n not in inside]


def merge_wrapped(body):
    """줄바꿈으로 이어진 목록 항목을 한 줄로 합친다.

    「… 노션 본문에」 다음 줄에 「로컬 절대경로 금지.」가 오는 형태를 줄 단위로 보면
    앞줄이 절단형으로 오판된다(실측). 행번호는 항목 첫 줄을 유지한다."""
    out = []
    for n, line in body:
        s = line.strip()
        prev_is_item = bool(out) and bool(LIST_HEAD.match(out[-1][1].strip()))
        cont = (prev_is_item and s and line[:1] in ' \t'
                and not LIST_HEAD.match(s) and s[0] not in '|>#')
        if cont:
            pn, pl = out[-1]
            out[-1] = (pn, pl.rstrip() + ' ' + s)
        else:
            out.append((n, line))
    return out


def wrapped_lines(body):
    """다음 줄이 본문으로 이어지는 줄의 번호를 모은다.

    `merge_wrapped` 는 **들여쓴** 목록 이어짐만 합친다. 들여쓰지 않은 문단 줄바꿈은
    남아서, 문장 중간에서 끊긴 줄이 절단형 종결로 잡힌다 — 실측으로 절단형 지적
    97건 중 49건(51%)이 이 형태였다.

    **합치지 않고 표시만 한다.** 합쳐서 다시 판정하면 오탐은 사라지지만 합친 안쪽의
    진짜 절단형이 영영 안 나온다. 없앨 수 없는 미탐을 만드는 쪽이라, 지우는 대신
    등급을 「의심」으로 내려 사람이 보는 칸으로 옮긴다.
    """
    marked = set()
    for i, (n, _) in enumerate(body[:-1]):
        nxt = body[i + 1][1].strip()
        if nxt and not _STRUCTURE_LINE.match(nxt):
            marked.add(n)
    return marked


def md_blocks(body):
    """연속한 목록 줄을 한 묶음으로 모은다 — 묶음 상한·강조 밀도·라벨 대조의 단위."""
    blocks, cur = [], []
    for n, line in body:
        if LIST_HEAD.match(line.strip()):
            cur.append((n, line))
        else:
            if line.strip() == '' and cur:
                blocks.append(cur); cur = []
            elif line.strip() and cur:
                blocks.append(cur); cur = []
    if cur:
        blocks.append(cur)
    return blocks


def scan_md(path, relaxed=False, form=None, rules=None):
    raw = io.open(path, encoding='utf-8').read()
    body = merge_wrapped(md_body(raw))
    err, warn = [], []
    slots = 0
    # 번호 붙은 제목 — § 없이 번호로 절을 가리킨 곳을 가르는 기준(`bare_section_hits`)
    md_heads = heading_numbers(l.strip().lstrip('#').strip() for _, l in body
                               if l.strip().startswith('#'))

    # 진입점 줄은 7번이 따로 본다 — 여기서 또 세면 같은 곳이 두 번 나온다
    lede_n = None
    _h1 = next((i for i, (n, l) in enumerate(body) if l.strip().startswith('# ')), None)
    if _h1 is not None:
        for n, l in body[_h1 + 1:_h1 + 8]:
            if l.strip() and not l.strip().startswith('#'):
                lede_n = n
                break

    # 1. 값·목록·표 칸·본문 문단의 서술형 종결
    md_mix = []          # 말투 섞임은 문서 전체를 봐야 해서 모았다가 끝에 판정한다
    wrapped = wrapped_lines(body)
    prev_is_table = contrast_table = False
    for n, line in body:
        s = line.strip()
        if s.startswith('>'):        # 인용은 아래 「해설을 인용 부호로 씀」에서 따로 본다
            continue
        is_table = s.startswith('|')
        # ❌/✅ 가 표 **머리**에만 있는 대조표 — 데이터 행이 곧 나쁜 예다. 표 단위로 뺀다
        if is_table and not prev_is_table:
            contrast_table = bool('❌' in s and '✅' in s)
        if not is_table:
            prev_is_table = False
        if is_example(s) or (is_table and contrast_table):
            prev_is_table = is_table
            continue
        if is_table:                 # 표 칸은 통째로 값이다 — 근거 문장이 올 자리가 아니다
            cells = [c.strip() for c in s.strip('|').split('|')]
            if set(''.join(cells)) <= set('-: '):
                prev_is_table = True
                continue
            parts, has_head = [[c.replace('**', '')] for c in cells], True
            # 표 머리의 금지 라벨
            if not prev_is_table:
                bad = [c.strip() for c in cells if c.replace('**', '').strip() in BAD_LABEL]
                if bad:
                    warn.append((n, '스캔 가치 없는 라벨',
                                 '표 머리 ' + ' · '.join(f'「{b}」' for b in bad)))
        elif LIST_HEAD.match(s):
            vals, has_head = split_value(LIST_HEAD.sub('', s, count=1))
            parts = [vals]
        elif CONCL_HEAD.match(s):
            vals, has_head = split_value(CONCL_HEAD.sub('', s, count=1))
            parts = [vals]
        elif s.startswith('#') or PARA_SKIP.match(s) or n == lede_n:
            # 제목은 아래 제목 검사, 진입점은 7번이 따로 본다.
            # 구분선·이미지·독립 링크는 값이 없는 줄이라 뺀다
            continue
        else:
            # 본문 문단도 값 슬롯이다 — 표·목록만 보면 규칙이 반만 적용된다.
            # 규칙 §형식 「왜·의도·근거는 문장 — 단 결론을 라벨 한 줄로 먼저」.
            # split_value가 그 구조를 이미 안다: 굵은 결론이 있으면 결론만 보고,
            # 뒤 근거 문장은 그대로 둔다. 결론이 없으면 문단 전체가 라벨 없는 설명이다.
            vals, has_head = split_value(s)
            parts = [vals]
        # 반말 서술형 — **문서에는 반말을 쓰지 않는다 · 전부**(2026-09-23 사용자).
        #   개조식이냐를 묻는 위 검사와 별개라 근거 문장까지 본다 — 근거 문장은
        #   개조식일 필요가 없지만 존댓말이어야 한다.
        #   ⛔ 예전에는 본문 문단만 봤다. 그래서 목록 속 「굵은 결론 — 근거 문장」의
        #      근거 문장은 개조식 검사에서도 빠지고 여기서도 빠져 **어느 검사에도 안
        #      걸렸다.** 목록·결론 줄·표 칸까지 본다. 대시 앞뒤는 HTML 처럼 따로 본다.
        speech = (cells if is_table
                  else [LIST_HEAD.sub('', s, count=1) if LIST_HEAD.match(s) else s])
        for text in speech:
            # ⛔ 인용을 **먼저** 가린다 — 문장부터 나누면 「…않는다. …아이디어다.」 같은
            #    여러 문장짜리 인용이 쪼개져 조각이 인용 밖으로 보이고, 남의 말 원문이
            #    반말로 걸린다(2026-09-23 이 저장소 피드백 문서에서 실측).
            for sent in sentences(mask(strip(text).replace('**', ''))):
                for part in re.split(r'\s+[—–]\s+', sent):
                    if is_plain_speech(part):
                        err.append((n, '반말 서술형', f'{part[:52]} — 존댓말로 쓰거나 개조식으로 끝낼 것'))
                        break
        prev_is_table = s.startswith('|')
        for cell in parts:
            for v in cell:
                slots += 1
                # 값 칸이 통째로 지시어 — 가리키는 것이 아예 안 적혔다.
                # 「| 검토 반영 | ✅ | 아래 |」 처럼 표 칸 하나가 「아래」뿐인 모양이다.
                # 여기서는 「아래」도 본다 — 문장 속과 달리 뒤따르는 것이 없다.
                if VAGUE_ONLY_RE.match(strip(v).strip()):
                    warn.append((n, '지시어 확인',
                                 f'{strip(v).strip()[:24]} — 값이 지시어뿐이다 · '
                                 '가리키는 것을 이름으로 적을 것'))
                fe, fw = (None, None) if all_quoted(v) else fragment(drop_tail(strip(v).replace('**', '')))
                if fe and n in wrapped:
                    # 다음 줄로 이어지는 문단이라 잘린 것인지 문장이 계속되는 것인지
                    # 줄만 봐서는 안 갈린다. **빼지 않고** 사람이 보는 칸으로 내린다.
                    warn.append((n, '절단형 의심',
                                 f'{v.strip()[:38]} — 다음 줄로 이어지는 문단이다 · '
                                 '문장이 계속되면 정상, 아니면 서술어가 빠진 것'))
                elif fe:
                    err.append((n, '절단형 종결', f'{v.strip()[:38]} — {fe}'))
                elif fw:
                    warn.append((n, '절단형 의심', f'{v.strip()[:38]} — {fw}'))
                for t in sentences(v):
                    md_mix.append((n, t))
                    if is_narrative(t):
                        # 머리 없이 마침표로 끝나는 항목 = 결론 라벨이 빠진 설명 문장.
                        # 규칙 §형식 「왜·근거는 문장 — 단 결론을 라벨 한 줄로 먼저」 위반이다.
                        bare = (not has_head) and EVIDENCE_END.search(t.strip())
                        msg = f'{t[:56]}'
                        if bare and relaxed:
                            warn.append((n, '결론 라벨 없는 설명', msg + ' — 결론을 라벨로 앞에 낼 것'))
                        elif bare:
                            err.append((n, '서술형 종결', msg + ' — 결론 라벨을 앞에 두거나 개조식으로 고칠 것'))
                        else:
                            err.append((n, '서술형 종결', msg))

    _mix_where = {t: n for n, t in md_mix}
    for sent, side, np, nq in register_mix([t for _n, t in md_mix]):
        warn.append((_mix_where.get(sent, 0), '말투 섞임',
                     f'{sent[:50]} — 이 문서는 존댓말 {np} · 반말 {nq} 이라 '
                     f'{side} 한 줄이 튄다'))

    # 2. 모호한 지칭 / 평가 수식어 — 코드·인용 구간과 대조 예시 줄은 뺀다
    for n, line in body:
        s = line.strip()
        if s.startswith('>') or is_example(s):
            continue
        m = mask(line)
        for w in VAGUE_HARD:
            if w in m:
                err.append((n, '모호한 지칭', f'「{w}」 — {excerpt(line, w, 52)}'))
        # 지시어 — 2026-09-18 부터 마크다운에서도 본다(위 VAGUE_SOFT 주석에 까닭).
        # 발췌는 **짚은 자리 둘레**를 낸다 — 줄머리를 내면 어디를 고칠지가 안 보인다.
        for hit in vague_hits(m):
            near = ' '.join(m[max(0, hit.start() - 24):hit.end() + 12].split())
            warn.append((n, '지시어 확인', f'{near[:46]} — {vague_note(hit.group(1))}'))
        for w in SELF_PRAISE:
            if w in m:
                warn.append((n, '평가 수식어', f'「{w}」 — {excerpt(line, w, 50)}'))
        for wrong, canon in BRANDS.items():
            if wrong in m:
                err.append((n, '제품 이름 음차',
                            f'「{wrong}」 → 「{canon}」 — {excerpt(line, wrong, 46)}'))
        for h in HOEGI.finditer(m):
            if HOEGI_OK.search(m[max(0, h.start() - 6):h.end() + 6]):
                continue
            err.append((n, '「회기」',
                        f'regression 이면 「회귀」 · 작업 단위면 「세션」·「회차」 — '
                        f'{excerpt(line, h.group(0), 40)}'))
        _hard = particle_veto(m, list(JARI.finditer(m)))
        if _hard:
            j = _hard[0]
            err.append((n, '「~하는 자리」',
                        f'「{j.group(0)}」 — {excerpt(line, j.group(0), 44)}'))
        else:
            _j = [q for q in JARI_ANY.finditer(m) if not JARI_OK.search(q.group(0))]
            for q in particle_veto(m, _j):
                warn.append((n, '「~하는 자리」 의심',
                             f'「{q.group(0)}」 — {excerpt(line, q.group(0), 42)}'))
        _e = [e for e in EMPTY_NOUN.finditer(m) if not EMPTY_NOUN_OK.search(e.group(0))]
        for e in particle_veto(m, _e):
            warn.append((n, '지어낸 명사구',
                         f'「{e.group(0)}」 — 그 명사가 혼자 서는지 볼 것 · '
                         f'{excerpt(line, e.group(0), 36)}'))
        for e in REACH_NOUN.finditer(m):
            err.append((n, '지어낸 명사구',
                        f'「{e.group(0)}」 — 도달·획득 용언 뒤의 빈 명사 · '
                        f'서술로 펼 것 · {excerpt(line, e.group(0), 34)}'))
        for e in COST_NOUN.finditer(m):
            err.append((n, '지어낸 명사구',
                        f'「{e.group(0)}」 — 「값이 들다」라 값이 목적어가 못 됨 · '
                        f'「비용」으로 · {excerpt(line, e.group(0), 30)}'))
        for e in time_hits(m):
            err.append((n, '지어낸 명사구',
                        f'「{e.group(0)}」 — 시점을 「~는 때」로 가리킴 · '
                        f'「시점」·「주기」로 바꿀 것 · {excerpt(line, e.group(0), 30)}'))
        for _pat, _better in NO_WORK_WORD:
            for e in _pat.finditer(m):
                err.append((n, '업무 글에 없는 말',
                            f'「{e.group(0)}」 — 업무 글에 안 쓰는 짝 · '
                            f'「{_better}」쪽으로 · {excerpt(line, e.group(0), 30)}'))
        for _pat, _better in NO_WORK_WORD_WARN:
            for e in _pat.finditer(m):
                warn.append((n, '업무 글에 없는 말',
                             f'「{e.group(0)}」 — 「{_better}」으로 풀어 쓸 것 · '
                             f'{excerpt(line, e.group(0), 30)}'))
        for e in MEASURED_WORD.finditer(m):
            warn.append((n, '업무 글에 없는 말',
                         f'「{e.group(0)}」 — 「측정값」·「측정한」이 흔함 · '
                         f'{excerpt(line, e.group(0), 30)}'))
        for kind, level, fix, hit in translationese_hits(m):
            note = f'「{hit.group(0)}」 — {fix} · {excerpt(line, hit.group(0), 40)}'
            (err if level == 'err' else warn).append((n, kind, note))
        for hit in misread_hits(m):
            warn.append((n, '다른 낱말로 읽힘',
                         f'「{hit.group(0)}」 — {MISREAD_FIX} · {excerpt(line, hit.group(0), 40)}'))
        for hit in section_ref_hits(line):
            err.append((n, '절 번호로 가리킴',
                        f'「{hit.group(0)}」 — {SECTION_FIX} · {excerpt(line, hit.group(0), 40)}'))
        if not line.lstrip().startswith('#'):
            for hit, title in bare_section_hits(line, md_heads):
                err.append((n, '절 번호로 가리킴',
                            f'{bare_section_note(hit, title)} · '
                            f'{excerpt(line, hit.group(0), 36)}'))

    # 3. 금지 라벨 (목록의 「라벨: 값」)
    for n, line in body:
        m = LABEL_COLON.match(line.strip().lstrip('-*').strip())
        if m and m.group(1).strip() in BAD_LABEL:
            warn.append((n, '스캔 가치 없는 라벨', f'「{m.group(1).strip()}」'))

    # 4. 반복 블록의 라벨 대조 — 같은 슬롯에 다른 말이 오는지
    label_sets = []
    for blk in md_blocks(body):
        labels = []
        for n, line in blk:
            if is_example(line):
                continue
            lm = LABEL_COLON.match(LIST_HEAD.sub('', line.strip(), count=1))
            if lm:
                labels.append(lm.group(1).strip())
        if len(labels) >= 2:
            label_sets.append(labels)
    if len(label_sets) >= 3:
        cnt = collections.Counter(x for s in label_sets for x in s)
        once = [k for k, v in cnt.items() if v == 1]
        if len(once) > len(label_sets) / 2:
            warn.append((0, '반복 블록 라벨 불일치',
                         f'{len(label_sets)}개 묶음에서 1회용 라벨 {len(once)}종: {", ".join(once[:6])}'))

    # 5. 제목·진입점 — 둘 다 명사형이어야 한다
    for n, line in body:
        hm = MD_HEADING.match(line.strip())
        if not hm:
            continue
        # ★ 꼬리를 떼기 **전** 원문을 sentences·is_narrative 에 넘긴다.
        # drop_tail 이 닫는 「」를 먼저 떼면 인용이 열린 채 남아 그 안의 서술형이
        # 제목의 종결이 된다 — 「「관찰한 사실은 LCT가 낸다」」가 오류로 났다
        # (2026-09-02 실측). 고유명 제목은 규칙상 개조식으로 고칠 수 없다.
        # HTML 경로(4b)와 같은 순서다 — 두 경로를 맞춘다.
        raw_title = strip(hm.group(1)).replace('**', '')
        for t in sentences(raw_title):
            if is_narrative(t):
                err.append((n, '제목 서술형', t[:56]))
        if not raw_title or all_quoted(raw_title):
            continue
        title = drop_tail(raw_title)
        fe, fw = fragment(title)
        if fe:
            err.append((n, '제목 명사형 위반', f'{title[:50]} — {fe}'))
        elif fw and '의문형' in fw:
            err.append((n, '제목 명사형 위반', f'{title[:50]} — {fw}'))
        elif fw:
            warn.append((n, '제목 형태 확인', f'{title[:50]} — {fw}'))

    h1 = next((i for i, (n, l) in enumerate(body) if l.strip().startswith('# ')), None)
    if h1 is not None:
        lede = None
        for n, l in body[h1 + 1:h1 + 8]:
            s = l.strip()
            if not s or s.startswith('#'):
                continue
            lede = (n, s); break
        if lede is None:
            err.append((0, '진입점 없음', '맨 앞에 「이 문서를 읽고 무엇을 하게 되나」 한 줄'))
        else:
            n, s = lede
            t = drop_tail(strip(LIST_HEAD.sub('', s, count=1).replace('**', '')))
            vals, _ = split_value(t)
            for v in vals:
                fe, fw = (None, None) if all_quoted(v) else fragment(drop_tail(v))
                if fe:
                    err.append((n, '진입점 명사형 위반', f'{v[:48]} — {fe}'))
                elif fw and '의문형' in fw:
                    err.append((n, '진입점 명사형 위반', f'{v[:48]} — {fw}'))
                elif fw:
                    warn.append((n, '진입점 형태 확인', f'{v[:48]} — {fw}'))
            if not is_example(s) and NARRATIVE.search(t) and not NOT_NARRATIVE.search(t):
                err.append((n, '진입점 서술형', t[:56]))

    # 6. 출처 없는 인용 블록 = 해설이다. 인용 부호만 썼을 뿐 값과 같은 규칙을 받는다
    #    ⛔ **코드펜스를 빼고 본다.** 예전에는 원문을 그대로 훑어서 코드 예시 안의
    #       `> [!NOTE]` 가 문서 본문으로 잡혔다(2026-09-16).
    lines = raw.split('\n')
    inside = fenced_lines(lines)
    i = 0
    while i < len(lines):
        if i in inside or not lines[i].strip().startswith('>'):
            i += 1; continue
        start, blk = i, []
        while (i < len(lines) and i not in inside
               and lines[i].strip().startswith('>')):
            blk.append(lines[i].strip().lstrip('>').strip()); i += 1
        if start < HEAD_LINES or ATTRIB.search(' '.join(blk)):
            continue
        for k, b in enumerate(blk):
            for chunk in re.split(r'(?<=다\.)\s+', b):
                c = strip(chunk).replace('**', '').strip()
                if c and NARRATIVE.search(c) and not NOT_NARRATIVE.search(c):
                    warn.append((start + k + 1, '해설을 인용 부호로 씀', f'{c[:52]} — 라벨:값으로 고칠 것'))

    # 한 줄에서 같은 종류가 여러 번 나오면 한 건으로 센다 — 건수가 고칠 곳 수와 어긋나지 않게
    #
    # ⛔ **낱말마다 고쳐야 하는 갈래는 예외다**(외부 검토 2026-09-18).
    #    「여기에 저장하고 거기에서 확인」은 이름을 **둘** 붙여야 하는데 한 건으로
    #    접혀 HTML(2건)과 갈렸다. 그 갈래만 발췌까지 열쇠에 넣는다.
    PER_HIT = {'지시어 확인'}

    def dedupe(items):
        seen, out = set(), []
        for n, kind, msg in items:
            key = (n, kind, msg) if kind in PER_HIT else (n, kind)
            if key in seen:
                continue
            seen.add(key)
            out.append((kind, f'{n}행  {msg}' if n else msg))
        return out

    err, warn = dedupe(err), dedupe(warn)

    # 형식은 선언으로만 정한다. 산문 비율로 짐작하면 표와 라벨이 뼈대인 문서까지
    # 산문으로 넘어가 정당한 지적이 조용히 사라진다(실측 65건이 그 구간이다).
    #
    # 물어보는 조건은 둘이다. 산문 비율 하나로는 **물음이 필요한 문서를 놓친다** —
    # 표와 목록이 뼈대이고 그 안의 설명만 산문인 문서는 비율이 낮게 나오는데,
    # 정작 개조식 지적이 쏟아지는 것이 그런 문서다(실측 41건 · 문서의 10%).
    # 그래서 **지적 자체가 개조식 축으로 쏠렸는지**도 함께 본다.
    narrative = sum(1 for item in err if (item[1] if len(item) == 3 else item[0]) == '서술형 종결')
    form_axis_flood = narrative >= NARRATIVE_ASK_MIN and narrative >= 0.5 * max(len(err), 1)
    resolved = form or declared_form(raw)
    if resolved is None and (prose_share(body) >= PROSE_ASK_THRESHOLD or form_axis_flood):
        warn.append((
            '형식 미표기',
            '산문으로 보이는데 형식을 안 적었다 — 머리말에 `form: prose` 를 적으면 '
            '개조식 검사를 빼고 본다. 개조식이 맞다면 `form: structured` 를 적는다.',
        ))
    # 코드펜스 안에 배포되는 한글 문구가 있으면 **안 봤다고 알린다.**
    #   ⛔ 지적이 아니라 안내다 — 펜스 안을 본문처럼 검사하면 바깥 문서의 개조식
    #      규약이 공지문에 걸린다(공지문은 산문이 정상이다).
    buried = fenced_prose(raw.split('\n'))
    if buried:
        warn.append((
            '펜스 안 배포 문구',
            f'코드펜스 안에 사람에게 나갈 것으로 보이는 한글 {buried}줄이 있다 — '
            '검사에서 빠졌다. 실제로 배포되는 글이면 파일로 빼서 따로 검사한다.',
        ))
    err, warn = apply_form(err, warn, resolved)
    err, warn = apply_instruction_file(err, warn, path)
    err, warn = apply_selection(err, warn, rules) if rules else (err, warn)
    return err, warn, slots


def main():
    argv = sys.argv[1:]
    if '--list-rules' in argv:
        list_rules(); return 0
    form, rules_path, taken = None, None, set()
    for i, a in enumerate(argv):
        if a == '--form' and i + 1 < len(argv):
            form = argv[i + 1].lower()
            taken.add(i + 1)          # 값이 파일 이름으로 새지 않게 뒤로 뺀다
        elif a.startswith('--form='):
            form = a.split('=', 1)[1].lower()
        elif a == '--rules' and i + 1 < len(argv):
            rules_path = argv[i + 1]
            taken.add(i + 1)
        elif a.startswith('--rules='):
            rules_path = a.split('=', 1)[1]
    if form is not None and form not in FORM_VALUES:
        print(f'--form 은 {" 또는 ".join(FORM_VALUES)} 만 받는다'); return 1
    # **모르는 플래그는 멈춘다.** 조용히 무시하면 `--relaxd` 처럼 한 글자 틀렸을 때
    # **끄려던 검사가 안 꺼진 채 통과로 읽힌다** — 사람은 껐다고 알고 있다.
    known = {'--html-only', '--relaxed', '-v', '--form',
             '--rules', '--no-rules', '--list-rules'}
    for i, a in enumerate(argv):
        if not a.startswith('-') or i in taken:
            continue
        if a in known or a.startswith('--form=') or a.startswith('--rules='):
            continue
        print(f'모르는 플래그 {a} — 쓸 수 있는 것: '
              f'{" · ".join(sorted(known))} · --form <structured|prose>')
        return 1

    args = [a for i, a in enumerate(argv) if not a.startswith('-') and i not in taken]
    html_only = '--html-only' in argv
    relaxed = '--relaxed' in argv
    verbose = '-v' in argv
    if not args:
        print(__doc__); return 1

    files = []
    for a in args:
        if os.path.isdir(a):
            files += glob.glob(os.path.join(a, '**', '*.html'), recursive=True)
            if not html_only:
                files += glob.glob(os.path.join(a, '**', '*.md'), recursive=True)
        else:
            files.append(a)

    # 갈래 설정 — 명시한 것이 먼저, 없으면 대상에서 위로 올라가며 찾는다.
    # `--no-rules` 는 발행 게이트용이다. 설정이 무엇을 끄든 전부 보게 한다.
    # (2026-09-23 까지는 기본으로 꺼 둔 반말 갈래를 켜는 일도 했다 — 그 장치는 걷어냈다.)
    rules = None
    if '--no-rules' in argv:
        rules = Selection(source='--no-rules')
    if '--no-rules' not in argv:
        found = rules_path or find_rules(args)
        if found:
            try:
                rules = load_rules(found)
            except (ValueError, OSError) as exc:
                print(f'갈래 설정을 못 읽었다 — {exc}'); return 1
            except ModuleNotFoundError:
                print('갈래 설정에는 Python 3.11 이상이 필요하다(tomllib)'); return 1
    elif rules_path:
        print('--rules 와 --no-rules 를 같이 줄 수 없다'); return 1

    # ⛔ 껐다는 사실이 안 보이면 「오류 0」이 무엇을 뜻하는지 알 수 없다.
    if rules:
        print(f'갈래 설정 {rules.source} — {rules.summary()}')
        for kind in sorted(rules.off):
            print(f'   ⊘ {kind} — 끔')
        for kind in sorted(rules.warn):
            print(f'   ↓ {kind} — 오류에서 주의로 낮춤')
        for kind in sorted(rules.err):
            print(f'   ↑ {kind} — 주의에서 오류로 올림')
        print()

    total_e = total_w = total_blind = 0
    for f in sorted(files):
        scan = scan_md if f.endswith('.md') else scan_html
        e, w, slots = scan(f, relaxed, form, rules)
        total_e += len(e); total_w += len(w)
        name = os.path.basename(f)
        if slots:
            if not e and not w:
                print(f'✅ {name}  (값 슬롯 {slots})'); continue
            head = f'\n── {name}  오류 {len(e)} · 주의 {len(w)}  (값 슬롯 {slots})'
        else:
            # 값 슬롯이 0이어도 지시어·진입점 검사는 돈다 — 그 결과를 숨기지 않는다
            total_blind += 1
            why = ''
            if not f.endswith('.md'):
                raw = io.open(f, encoding='utf-8', errors='ignore').read()
                if sum(len(m) for m in re.findall(r'<script.*?</script>', raw, re.S)) > 20000:
                    why = ' · JS 렌더로 보임(정적 검사의 한계 — 렌더된 화면으로 확인할 것)'
            head = f'\n⛔ {name} — 값 슬롯 미인식, 부분 검사만 됨. 합격이 아니다{why}'
            if not e and not w:
                print(head.lstrip('\n')); continue
        print(head)
        for kind, msg in e:
            print(f'   ❌ [{kind}] {msg}')
        for kind, msg in (w if verbose else w[:8]):
            print(f'   ⚠️  [{kind}] {msg}')
        if not verbose and len(w) > 8:
            print(f'   … 주의 {len(w)-8}건 더 (-v)')

    tail = f' · 검사 불가 {total_blind}' if total_blind else ''
    # 합계만 잘라 보는 사람이 많다. 설정으로 줄어든 수라는 것을 여기서도 적는다.
    if rules:
        tail += f' · 갈래 설정 적용({rules.summary()})'
    # ⛔ 좁게 본 것이 통과로 읽히면 안 된다 — 「끈 갈래를 적는다」와 같은 이유다.
    if FELL_BACK:
        tail += ' · 형태소 분석기 없이 본 곳 있음'
        print('\n형태소 분석기 없음 — 「~는 때」를 용언 목록으로만 봤습니다 · 미탐이 섞입니다'
              '\n   고치려면 python -m pip install kiwipiepy')
    # ⛔ 목록이 없으면 그 갈래를 **안 본 것**이다. 조용히 넘기면 「오류 0」이 통과인지
    #    안 본 것인지 갈리지 않는다 — 껐다는 사실을 적는 규칙과 같은 이유다.
    if not BRANDS:
        tail += ' · 제품 이름 안 봄'
        print(f'\n제품 이름 목록이 없어 음차는 안 봤습니다 — 이름은 저장소 밖에 둡니다'
              f'\n   만들려면 data/catalog/local-brand-names.example.txt 를 '
              f'{BRAND_FILE} 로 복사하십시오')
    print(f'\n합계 — 오류 {total_e} · 주의 {total_w}{tail}')
    return 1 if total_e else 0


if __name__ == '__main__':
    sys.exit(main())
