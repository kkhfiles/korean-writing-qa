# 실측 176개 문서 — 「의문사 + 하나」 96건 중 수사는 1건이고 그 의문사가 「어느」였다.
QWORD_STRONG = re.compile(r'(무엇|뭐|어디|언제|누가|누구|왜|어떻게)')
QEND_HANA = re.compile(r'하나$')


def fragment(t):
    """값 하나를 보고 (오류 사유, 주의 사유)를 낸다. 해당 없으면 (None, None)."""
    t = t.strip()
    if not t or PROPER.match(t):
        return None, None
    if JOSA_CUT.search(t) and not TIME_PHRASE.search(t):
        return '조사로 끝나 서술어가 잘렸다 — 명사로 끝내거나 서술 명사를 붙일 것', None
    if QWORD.search(t) and QEND_HARD.search(t):
        return '라벨을 의문문으로 썼다 — 명사구로(「무엇을 보나」→「관측 대상」)', None
    if QWORD_STRONG.search(t) and QEND_HANA.search(t):
        return '라벨을 의문문으로 썼다 — 명사구로(「무엇을 보나」→「관측 대상」)', None
    if JOSA_SOFT.search(t) and not LO_WORD.search(t):
        return None, '조사 종결로 보인다 — 값이면 명사로 끝낼 것'
    if QWORD.search(t) and QEND_SOFT.search(t):
        return None, '의문형 라벨 — 명사구가 나은지 볼 것'
    return None, None


def mask(line):
    """지시어·수식어 검사용 — 코드·인용 구간을 지운다."""
    return QUOTE_SPAN.sub(' ', CODE_SPAN.sub(' ', line))


#: **칸을 가르는** 태그 — 여기가 끊기면 다른 값이다. 자리에 줄바꿈을 남긴다.
#: 인라인(`b`·`span`·`a`·`code`)은 화면에서도 붙어 보이므로 지우기만 한다.
BLOCK_TAG = re.compile(
    r'</?(?:p|div|dl|dt|dd|li|ul|ol|table|thead|tbody|tr|th|td|section|article|'
    r'h[1-6]|header|footer|nav|aside|main|figure|figcaption|blockquote|pre|hr)'
    r'\b[^>]*>', re.I)
#: ⛔ **`<br>` 는 칸 경계가 아니다** — 한 칸 **안에서** 줄만 바꾼 것이라 값은 이어진다.
#:    처음에 이것도 줄바꿈으로 바꿨다가 `<dd>커밋을<br>걷음</dd>` 의
#:    「업무 글에 없는 말」 오류가 사라졌다(문맥 창이 `[^\n]{0,10}` 이라 줄을 못 넘는다).
#:    **화면에서 줄만 나눴는데 판정이 달라지면 안 된다** — 빈칸으로 바꾼다.
#:    제목 검사는 `strip` 앞에서 `<br>` 로 직접 쪼개므로 영향을 안 받는다.
INLINE_BREAK = re.compile(r'<br\b[^>]*>', re.I)


def strip(x):
    """태그를 떼고 글자만 낸다 — **덩어리 태그 자리에는 줄바꿈을 남긴다.**

    ⚠️ 예전에는 모든 태그를 빈 문자열로 지워 `<dt>쓰는 곳</dt><dd>사내 메신저`
    가 **「쓰는 곳사내 메신저」**로 붙었다. 화면에서는 두 줄인데 검사기에는 한
    낱말로 보인다 — 발췌가 그렇게 나가면 읽는 사람이 **없는 자리를 찾는다.**

    지적 자체는 안 바뀐다(HTML 84개 실측 2026-09-18 — 새로 나는 것 0 · 가려졌던
    것 0). 고치는 값은 **사람이 읽는 발췌**와, 문맥 창(`[^·\\n]{0,26}`)이 칸을
    넘지 못하게 되는 것 둘이다.
    """
    return re.sub(r'<[^>]+>', '',
                  BLOCK_TAG.sub('\n', INLINE_BREAK.sub(' ', x))).strip()


def drop_tail(t):
    """꼬리 괄호·상호참조·강조 표시를 뗀다 — 「…남는다 (부록 E)」의 서술형을 가리지 않도록.

    서술형 판정이 **끝 앵커**라 값 끝에 붙은 강조 표시가 그것을 가린다.
    「**…하나로 정해진다**」가 마크다운 표 칸에서 통과했다(2026-08-14 실측).
    split_value의 EVIDENCE_END 판정이 이미 같은 집합을 떼고 있다 — 여기와 맞춘다."""
    t = t.strip()
    while TAIL.search(t):
        t = TAIL.sub('', t).strip()
    return t.rstrip('"\'』」)*_`~”’')


PROPER = re.compile(r'^[「『][^」』]+[」』]$')   # 값 전체가 고유명 표기


def all_quoted(t):
    """값 전체가 인용·고유명 표기인가 — 그러면 개조식으로 고칠 수 없다(규칙 §1).

    「」로 감싼 값 = 고유명(원칙 이름·문서 제목·정해진 문구)이고,
    따옴표 안의 서술형은 **인용된 문구**다 — 값이 아니라 이름처럼 다룬다.
    인용을 지우고 남는 게 없으면 값 전체가 인용이다: 「"규칙을 썼다" ≠ "규칙이 적용된다"」
    drop_tail 이 닫는 따옴표를 떼기 **전에** 본다 — 떼고 나면 인용 안 서술형이 노출된다.
    강조 표시는 인용 바깥에 붙으므로 함께 뗀다 — 「*"어디에 물어보나"*」가 그 형태다.
    """
    base = strip(t).replace('**', '').strip(' *_`~')
    if PROPER.match(base):
        return True
    # 꼬리 괄호는 출처 표기다 — 「"…한다" (여러 블로그)」의 인용을 가리면 안 된다.
    # 인용 판정에서만 뗀다(값 판정은 drop_tail 이 따로 한다).
    for cand in (base, TAIL.sub('', base).strip(' *_`~')):
        if PROPER.match(cand) or QUOTE_SPAN.sub(' ', cand).strip(' ≠=·-—*_`~') == '':
            return True
    return False


def excerpt(line, found, width):
    """지적 발췌 — 걸린 말이 앞머리에 안 들면 그 둘레를 보인다.

    ⛔ 예전에는 줄 앞머리만 잘라서 긴 표 행에서는 걸린 말이 발췌에 안 보였다 —
       「「맡음」 — … · | **1층 · 낱말** | `skills/finali」처럼 읽는 사람이 어디를
       고치라는 것인지 줄을 다시 열어 찾아야 했다(2026-09-23).
    """
    text = strip(line).strip()
    at = text.find(found)
    if at < 0 or at + len(found) <= width:
        return text[:width]
    begin = max(0, at - width // 3)
    return '…' + text[begin:begin + width]


def is_narrative(sent):
    """값의 종결이 서술형인가 — **인용 안의 서술형은 값의 종결이 아니다**(규칙 §1).

    drop_tail 이 닫는 괄호를 떼면 인용 안 서술형이 값의 끝으로 노출된다.
    「… 담당 팀 판단이 「도입 장벽이 가장 낮다」」가 그 형태다(2026-08-14 실측).
    인용을 지운 자리에서 종결을 본다 — 인용 밖이 명사형이면 값은 개조식이다.
    ★ 순서가 중요하다 — **인용을 먼저 지우고 꼬리를 뗀다.** 거꾸로 하면
    닫는 괄호가 먼저 떨어져 인용이 열린 채 남고 그 안의 서술형이 값의 끝이 된다."""
    probe = drop_tail(QUOTE_SPAN.sub(' ', sent))
    return bool(NARRATIVE.search(probe)) and not NOT_NARRATIVE.search(probe)


def is_plain_speech(sent):
    """서술 문장이 반말인가 — 「니다」·「요」 계열이 아니면 반말이다.

    **서술형인지부터 본다.** 명사로 끝나는 개조식 값은 대상이 아니다. 「~습니다」도
    「다」로 끝나므로 `is_narrative` 는 존댓말까지 참을 낸다 — 그 안에서 다시 가른다.

    **문서에는 반말을 쓰지 않는다 — 전부**(2026-09-23 사용자). 예전에는 「업무
    보고서의 63%가 반말이고 그게 정상」이라며 기본으로 꺼 두었는데 빈도 논증이었다.
    Claude 만 읽는 지시 파일만 뺀다(`is_instruction_file`).
    """
    probe = drop_tail(QUOTE_SPAN.sub(' ', sent)).rstrip('.!?… ')
    return is_narrative(sent) and not is_polite(probe)


# 말투 섞임 — 한 문서 안에서 존댓말과 반말이 함께 나오나.
#   한 줄만 튀는 것을 따로 짚는다 — 존댓말로 쓰다 한 줄만 반말로 빠지면 읽는
#   사람이 거기서 걸린다(2026-09-09 사용자 — 「갑자기 반말로」).
#   이 갈래가 생길 때는 「반말 서술형」이 기본으로 꺼져 있어 그 빈 곳을 메웠다.
#   2026-09-23 부터 반말은 문서 전부에서 오류다. 이 갈래는 **어느 줄이 튀는지**를
#   알려 주는 주의로 남는다 — 반말 문서에 존댓말 한 줄이 튀는 반대 경우도 본다.
#
#   ⚠️ 실측 2026-09-09 — 섞임은 드물다. 사용자 메일 796건 중 12 · 노션 3,000건 중
#   27 · 공개 소개 쪽 9건 중 0. 소음이 되지 않는다.
#   ⚠️ **주의로만 낸다** — 남의 말을 그대로 옮긴 인용과 대조 예시가 섞여 있어
#   기계가 마지막까지 못 가른다.
MIX_MIN = 12          # 서술 문장이 이보다 적으면 판단하지 않는다
MIX_SHARE = 0.25      # 소수 쪽이 이보다 크면 「섞임」이 아니라 두 말투를 쓴 문서다


def register_mix(sents):
    """존댓말과 반말이 섞였으면 **소수 쪽** 문장을 낸다."""
    polite, plain = [], []
    for s in sents:
        if is_plain_speech(s):
            plain.append(s)
        elif is_narrative(s):
            polite.append(s)
    total = len(polite) + len(plain)
    if total < MIX_MIN or not polite or not plain:
        return []
    minor = polite if len(polite) < len(plain) else plain
    if len(minor) / total >= MIX_SHARE:
        return []
    side = '존댓말' if minor is polite else '반말'
    return [(s, side, len(polite), len(plain)) for s in minor]


def sentences(t):
    """값 하나를 문장 단위로 쪼갠다 — 마지막 문장만 보면 앞 문장의 서술형을 놓친다."""
    if all_quoted(t):
        return []
    # 꼬리를 여기서 떼지 않는다 — 인용을 지우기 전에 닫는 괄호가 떨어지면
    # 인용 안 서술형이 값의 끝으로 노출된다(is_narrative 가 순서를 지킨다).
    out = []
    for chunk in re.split(r'(?<=다\.)\s+', strip(t)):
        c = chunk.strip()
        if c and not set(c) <= set('-: '):
            out.append(c)
    return out


def split_value(c):
    """검사 대상 조각과 그 구조를 낸다 — (조각들, 굵은머리 있나).

    「굵은 결론 + 근거 문장」이면 결론만 본다. 표 칸에는 쓰지 않는다 —
    표는 그 자체가 값 슬롯이라 근거 문장이 올 자리가 아니다.

    ⚠️ **「근거가 한 문장이면 값으로 본다」를 규칙으로 만들지 말 것**(2026-09-07 실측).
    굵은 머리 뒤가 한 문장인데 서술형으로 끝나는 것을 값으로 치면 실문서 176개에서
    **539건**이 새로 걸린다. 표본을 읽어 보면 대부분 정당한 근거 문장이고
    `CLAUDE.md` 자신도 여기 걸린다 — 문장 수로는 값과 근거가 갈리지 않는다.
    오탐이 섞이면 아무도 안 보므로 침묵을 유지한다. **이 구분은 사람이 읽고 가른다.**"""
    c = LEAD_MARK.sub('', c.strip())
    lm = LABEL_COLON.match(c)
    if lm:
        # 콜론 뒤는 값이다. 「굵은 결론 — 근거 문장」 예외를 콜론 값에 적용하면
        # 「**상태**: 공개자료를 확인한다.」 같은 서술형 값이 빠진다.
        return [x.replace('**', '') for x in (lm.group(1), lm.group(2)) if x.strip()], True
    m = BOLD_HEAD.match(c)
    if not m:
        return [c.replace('**', '')], False
    head, rest = m.group(1), m.group(2).strip()
    # 마침표 뒤에 강조 표시·닫는 따옴표가 붙으면 원문 그대로는 마침표를 못 찾는다.
    # 「… 하지 않는다.**」 「… 인가."*」 가 근거 문장으로 인정되지 않아 오탐이 났다(실측).
    if rest and EVIDENCE_END.search(rest.rstrip('*_`~"”’\'」』 ')):
        return [head.replace('**', '')], True
    return [x.replace('**', '') for x in (head, rest) if x.strip()], True


# ── HTML ─────────────────────────────────────────────────────────────────────
def scan_html(path, relaxed=False, form=None, rules=None):
    raw = io.open(path, encoding='utf-8').read()
    # base64 등 초장문 줄 제외 → 그 안의 우연한 일치를 오탐으로 세지 않는다
    body = '\n'.join(l for l in raw.split('\n') if len(l) < 800)
    body = re.sub(r'<style.*?</style>', ' ', body, flags=re.S)
    body = re.sub(r'<script.*?</script>', ' ', body, flags=re.S)   # 코드는 문서가 아니다
    # 코드는 문서가 아니다 — 마크다운은 코드펜스와 인라인 코드를 처음부터 뺐는데
    # HTML 경로만 안 빼서 **같은 내용이 형식에 따라 다르게 판정됐다**(2026-09-07).
    # 제목 검사(09-02)·문단 검사(09-04)에 이어 세 번째로 같은 모양의 결함이다.
    #
    # ⛔ **맨 `<pre>` 는 빼지 않는다.** 처음에 `<pre>` 를 통째로 뺐다가 업무 칸반 한 장에서
    #    지적 44건이 사라지는 것을 보고 좁혔다 — 그 파일의 `<pre>` 33개는 코드가 아니라
    #    공백을 살리려고 감싼 한국어 기록이었다. HTML 에서 코드 의미를 지는 것은 `<code>`
    #    이고, 마크다운 코드펜스에 대응하는 것은 `<pre><code>` 다.
    #
    # 빈칸이 아니라 표시를 남긴다 — 값이 코드뿐인 칸이 사라지면 슬롯 수가 줄고,
    # 0이 되면 「값 슬롯 미인식」으로 넘어간다. 그건 못 본 것이 아니라 정당하게 뺀 것이다.
    # 지우기 **전에** 배포 문구가 들었는지 센다 — 지운 뒤에는 안 보인다.
    buried = pre_code_prose(body)
    body = re.sub(r'(<pre[^>]*>)\s*<code[^>]*>.*?</code>\s*(</pre>)', r'\1code\2',
                  body, flags=re.S | re.I)
    body = re.sub(r'(<code[^>]*>).*?(</code>)', r'\1code\2', body, flags=re.S | re.I)
    err, warn = [], []
    slots = 0
    if buried:
        warn.append((
            '펜스 안 배포 문구',
            f'`<pre><code>` 안에 사람에게 나갈 것으로 보이는 한글 {buried}줄이 있다 — '
            '검사에서 빠졌다. 실제로 배포되는 글이면 파일로 빼서 따로 검사한다.',
        ))

    # 1. 값·목록·표 칸의 서술형 종결
    for tag in ('dd', 'li', 'td'):
        for x in re.findall(rf'<{tag}[^>]*>(.*?)</{tag}>', body, re.S):
            t = strip(x)
            if not t:
                continue
            slots += 1
            if is_example(t):
                continue
            if VAGUE_ONLY_RE.match(t.strip()):
                warn.append(('지시어 확인',
                             f'{t.strip()[:24]} — 값이 지시어뿐이다 · '
                             '가리키는 것을 이름으로 적을 것'))
            # 「굵은 결론 — 근거 문장」이면 결론만 본다(규칙 §1).
            # **목록 항목에만** 적용한다 — 표 칸(td)·값 칸(dd)은 그 자체가 값 슬롯이라 예외가 없다
            if tag == 'li':
                # 줄머리 기호(⚠️ ★ 📌 …)를 떼고 굵은 머리를 찾는다 — 문단 경로와 같다.
                m = re.match(r'\s*<(b|strong)[^>]*>(.*?)</\1>(.*)$', LEAD_MARK.sub('', x.strip()), re.S)
                if m and EVIDENCE_END.search(strip(m.group(3))):
                    t = strip(m.group(2))
            # 값 하나에 문장이 둘이면 끝 문장만 봐서는 앞 문장을 놓친다.
            # 마크다운 경로는 sentences()로 쪼개는데 여기만 안 쪼개고 있었다(2026-08-14 실측).
            # sentences()가 고유명 「」·인용 전체 예외도 함께 처리한다 — 두 경로를 맞춘다.
            for sent in sentences(t):
                if is_narrative(sent):
                    err.append(('서술형 종결', f'<{tag}> {sent[:58]}'))
            fe, fw = (None, None) if all_quoted(t) else fragment(drop_tail(t))
            if fe:
                err.append(('절단형 종결', f'{t[:40]} — {fe}'))
            elif fw:
                warn.append(('절단형 의심', f'{t[:40]} — {fw}'))

    # 1b. 실측 관례 — 라벨/값을 `class="k"` / `class="v…"` 로 쓴 아티팩트가 다수다
    #     (로컬 아티팩트 58개 중 값 슬롯 미인식 31개, 그중 24개가 이 관례)
    for x in re.findall(r'<[a-zA-Z]+[^>]*class="v(?:\s[^"]*)?"[^>]*>(.*?)</[a-zA-Z]+>', body, re.S):
        t = strip(x)
        if not t:
            continue
        slots += 1
        if is_example(t):
            continue
        if VAGUE_ONLY_RE.match(t.strip()):
            warn.append(('지시어 확인',
                         f'{t.strip()[:24]} — 값이 지시어뿐이다 · '
                         '가리키는 것을 이름으로 적을 것'))
        for sent in sentences(t):
            if is_narrative(sent):
                err.append(('서술형 종결', f'class=v {sent[:58]}'))
        fe, fw = (None, None) if all_quoted(t) else fragment(drop_tail(t))
        if fe:
            err.append(('절단형 종결', f'{t[:40]} — {fe}'))
        elif fw:
            warn.append(('절단형 의심', f'{t[:40]} — {fw}'))
    for lab in re.findall(r'<[a-zA-Z]+[^>]*class="k(?:\s[^"]*)?"[^>]*>(.*?)</[a-zA-Z]+>', body, re.S):
        if strip(lab) in BAD_LABEL:
            warn.append(('스캔 가치 없는 라벨', strip(lab)))

    # 2. 지시어·평가 수식어 — 코드·인용 구간은 뺀다
    text = mask(strip(body))
    for w in VAGUE_HARD:
        for m in re.findall(r'[^·\n]{0,26}' + w + r'[^·\n]{0,20}', text):
            if is_example(m):
                continue
            err.append(('모호한 지칭', f'「{w}」 … {m.strip()[:58]}'))
    for w in SELF_PRAISE:
        for m in re.findall(r'[^·\n]{0,20}' + w + r'[^·\n]{0,22}', text):
            warn.append(('평가 수식어', f'「{w}」 … {m.strip()[:56]} — 무엇을 하는지로 바꿀 것'))
    for wrong, canon in BRANDS.items():
        for m in re.finditer(re.escape(wrong), text):
            near = ' '.join(text[max(0, m.start() - 18):m.end() + 18].split())
            err.append(('제품 이름 음차', f'「{wrong}」 → 「{canon}」 · {near[:48]}'))
    for kind, level, fix, hit in translationese_hits(text):
        near = ' '.join(text[max(0, hit.start() - 20):hit.end() + 20].split())
        (err if level == 'err' else warn).append(
            (kind, f'「{hit.group(0)}」 — {fix} · {near[:48]}'))
    for hit in misread_hits(text):
        near = ' '.join(text[max(0, hit.start() - 20):hit.end() + 20].split())
        warn.append(('다른 낱말로 읽힘', f'「{hit.group(0)}」 — {MISREAD_FIX} · {near[:48]}'))
    _raw = strip(body)          # 원문 — 「영어 제목」 §N 을 가리려면 인용이 보여야 한다
    for hit in section_ref_hits(_raw):
        near = ' '.join(_raw[max(0, hit.start() - 20):hit.end() + 20].split())
        err.append(('절 번호로 가리킴', f'「{hit.group(0)}」 — {SECTION_FIX} · {near[:48]}'))
    _heads = heading_numbers(strip(h) for h in
                             re.findall(r'<h[1-6][^>]*>(.*?)</h[1-6]>', body, re.S))
    _body_only = re.sub(r'<h[1-6][^>]*>.*?</h[1-6]>', ' ', body, flags=re.S)
    _body_raw = strip(_body_only)
    for hit, title in bare_section_hits(_body_raw, _heads):
        near = ' '.join(_body_raw[max(0, hit.start() - 20):hit.end() + 12].split())
        err.append(('절 번호로 가리킴', f'{bare_section_note(hit, title)} · {near[:40]}'))
    # 문맥 조각은 **한 줄로 눌러서** 낸다 — HTML 본문에는 줄바꿈이 섞여 있어
    # 그대로 두면 보고서가 여러 줄로 쪼개지고, 훅이 첫 줄만 걷어 가 정작
    # 문제 문장이 사라진다(오류는 뜨는데 어디인지 모르는 상태가 된다).
    def around(m):
        return ' '.join(text[max(0, m.start() - 24):m.end() + 8].split())
    for m in vague_hits(text):
        warn.append(('지시어 확인', f'{around(m)[:52]} — {vague_note(m.group(1))}'))
    for m in particle_veto(text, list(JARI.finditer(text))):
        err.append(('「~하는 자리」', f'{around(m)[:56]} — 지점·위치·사례·단계·시점 중 맞는 말로 바꿀 것'))
    _jari = [m for m in JARI_ANY.finditer(text)
             if not (JARI.search(m.group(0)) or JARI_OK.search(m.group(0)))]
    for m in particle_veto(text, _jari):
        warn.append(('「~하는 자리」 의심', f'{around(m)[:56]} — 사람이 모이는 뜻이 아니면 바꿀 것'))
    _empty = [m for m in EMPTY_NOUN.finditer(text) if not EMPTY_NOUN_OK.search(m.group(0))]
    for m in particle_veto(text, _empty):
        warn.append(('지어낸 명사구',
                     f'{around(m)[:56]} — 그 명사가 혼자 서는지 볼 것 · 아니면 문장을 서술로 펼 것'))
    for m in REACH_NOUN.finditer(text):
        err.append(('지어낸 명사구',
                    f'{around(m)[:56]} — 도달·획득 용언 뒤의 빈 명사 · 서술로 펼 것(닿는 값 → 달성 가능)'))
    for m in COST_NOUN.finditer(text):
        err.append(('지어낸 명사구',
                    f'{around(m)[:56]} — 「값이 들다」라 값이 목적어가 못 됨 · 「비용」으로'))
    for m in time_hits(text):
        err.append(('지어낸 명사구',
                    f'{around(m)[:56]} — 시점을 「~는 때」로 가리킴 · 「시점」·「주기」로 바꿀 것'))
    for _pat, _better in NO_WORK_WORD:
        for m in _pat.finditer(text):
            err.append(('업무 글에 없는 말',
                        f'{around(m)[:56]} — 업무 글에 안 쓰는 짝 · 「{_better}」쪽으로'))
    for _pat, _better in NO_WORK_WORD_WARN:
        for m in _pat.finditer(text):
            warn.append(('업무 글에 없는 말',
                         f'{around(m)[:56]} — 「{_better}」으로 풀어 쓸 것'))
    for m in MEASURED_WORD.finditer(text):
        warn.append(('업무 글에 없는 말',
                     f'{around(m)[:56]} — 「측정값」·「측정한」이 흔함'))
    for m in HOEGI.finditer(text):
        span = text[max(0, m.start() - 6):m.end() + 6]
        if HOEGI_OK.search(span):
            continue
        err.append(('「회기」', f'{around(m)[:56]} — regression 이면 「회귀」 · '
                               '작업 단위면 「세션」·「회차」'))

    # 3. 금지 라벨
    #    ⛔ **표 머리(`<th>`)도 라벨이다**(2026-09-18). 여기 `<dt>` 만 있어서
    #       마크다운의 `| 항목 | 비고 |` 은 잡히는데 같은 표를 HTML 로 쓰면
    #       통과했다. 형식이 판정을 바꾸면 사람은 **통과한 쪽만 보고 발행한다.**
    for lab in re.findall(r'<(?:dt|th)[^>]*>(.*?)</(?:dt|th)>', body, re.S):
        if strip(lab) in BAD_LABEL:
            warn.append(('스캔 가치 없는 라벨', strip(lab)))

    # 4. 서술형 문단 — 마크다운과 같은 판정을 쓴다.
    #
    #   ⛔ 2026-09-04 이전에는 **길이만 봤다**(`len(t) > 90` → 주의). 이름은
    #      「서술형 문단」인데 서술형인지를 안 본 것이다. 그래서 두 방향으로 틀렸다.
    #
    #      ① **미탐** — 짧은 서술 문단을 통째로 놓쳤다. 같은 내용을 두 형식에 넣어
    #         재니 마크다운은 오류 2, HTML 은 **오류 0 · 주의 0** 이었다
    #         (「이 문서는 설계 전용이다.」·「표는 그 자체가 값 슬롯이라 …이 아니다.」).
    #      ② **오탐** — 「굵은 결론 — 근거 문장」이 길다는 이유로 걸렸다. 규칙이
    #         허용하는 형태인데 지적이 나서 다른 주의를 덮었다(실측 251건).
    #
    #   고친 뒤 실측(HTML 전수) — 주의 319 → 68 · 오류 29 → 195. 새 오류 166건은
    #   파일 넷에 몰려 있고 127건이 발표 대본이다(산문이라 `form: prose` 소관).
    #   나머지는 **내가 쓴 굵은 결론이 서술형**이었던 것 — 규칙대로 걸린 것이다.
    #
    #   `<p` 뒤에 글자가 오면 <pre>·<path> 같은 다른 태그다 — 문단만 본다.
    for p in re.findall(r'<p(?![a-zA-Z])(?![^>]*class="(?:lede|sub)")[^>]*>(.*?)</p>', body, re.S):
        t = strip(p)
        if not t or is_example(t):
            continue
        # 「굵은 결론 — 근거 문장」이면 결론만 본다(규칙 §1) — 목록 항목과 같은 처리다.
        #
        #   ⛔ 2026-09-08 이전에는 `<b>` 로 **시작할 때만** 이 예외를 줬다. 그래서
        #      「⚠️ **결론** — 근거 문장.」처럼 줄머리 기호가 앞에 붙으면 예외를 못 받고
        #      근거 문장이 통째로 오류가 됐다. 마크다운 경로는 진작 `LEAD_MARK` 로
        #      기호를 떼고 굵은 머리를 찾는데(§split_value) **여기만 안 뗐다** —
        #      같은 문장을 두 형식에 넣어 재면 마크다운 0 · HTML 1 로 갈렸다(실측).
        #      기호를 떼도 굵은 머리 자체는 그대로 `is_narrative` 로 본다 — 결론이
        #      서술형이면 여전히 걸린다. 예외가 넓어지는 것은 **근거 문장 쪽뿐**이다.
        m = re.match(r'\s*<(b|strong)[^>]*>(.*?)</\1>(.*)$', LEAD_MARK.sub('', p.strip()), re.S)
        if m and EVIDENCE_END.search(strip(m.group(3))):
            t = strip(m.group(2))
        for sent in sentences(t):
            if is_narrative(sent):
                err.append(('서술형 문단', sent[:58]))

    # 4c. 반말 서술형 — 문서에는 반말을 쓰지 않는다 · 전부(2026-09-23 사용자).
    #
    #   위 4번과 대상이 다르다 — 여기서는 `lede`·`sub` 도 보고, 「굵은 결론 —
    #   근거 문장」의 **근거 문장까지** 본다. 4번은 개조식이냐를 묻고 여기서는
    #   말투를 묻기 때문이다. 근거 문장은 개조식일 필요가 없지만 존댓말이어야 한다.
    #
    #   ⛔ 한국어 제품 홍보 쪽에 반말은 안 쓴다. 같이 만든 소개 쪽 셋은 서술 문장이
    #      100% 존댓말인데 사례집 하나만 67건이 반말이었다(2026-09-08 실측) —
    #      만든 사람의 작업 문서 말투가 그대로 나간 것이다.
    #   ⛔ `<p>` 만 보면 꼬리말을 놓친다 — 발행한 쪽의 꼬리말이 `<span>` 으로만
    #      짜여 있어 반말 한 줄이 그대로 나갔다(2026-09-08 · 사람이 읽고서야 걸림).
    #      꼬리말은 사람이 보는 글이므로 함께 본다.
    chunks = re.findall(r'<p(?![a-zA-Z])[^>]*>(.*?)</p>', body, re.S)
    chunks += re.findall(r'<footer[^>]*>(.*?)</footer>', body, re.S)
    # ⛔ **문서 전부**(2026-09-23 사용자) — 목록·정의·표 칸·그림 설명도 사람이 읽는
    #    글이다. `<p>` 와 꼬리말만 보던 동안 목록 속 근거 문장의 반말이 어느 검사에도
    #    안 걸렸다. 말투 섞임은 예전 범위(문단·꼬리말)로 센다 — 판정 기준이 그 범위로
    #    잡혀 있다.
    slot_chunks = [m.group(2) for m in re.finditer(
        r'<(li|dd|td|figcaption)(?![a-zA-Z])[^>]*>(.*?)</\1>', body, re.S)]
    mix_sents, told = [], set()
    for p, count_mix in [(c, True) for c in chunks] + [(c, False) for c in slot_chunks]:
        t = strip(p)
        if not t or is_example(t):
            continue
        # 대시 앞뒤를 따로 본다 — 「이 페이지도 통과했다 — 오류 0.」 처럼 반말이
        # 대시 앞에 있으면 문장의 끝이 아니라서 통째로 빠진다(2026-09-08 실측).
        # 개조식 결론 머리(「대체 아님 — …」)는 서술형이 아니라 그대로 지나간다.
        if count_mix:
            mix_sents.extend(sentences(t))
        # 인용을 먼저 가리고 나눈다 — 여러 문장짜리 인용의 조각이 반말로 걸리지 않게
        for sent in sentences(mask(t)):
            for part in re.split(r'\s+[—–]\s+', sent):
                if is_plain_speech(part):
                    # 겹친 태그(`<li><p>…</p></li>`)에서 같은 문장이 두 번 나오지 않게
                    if part not in told:
                        told.add(part)
                        err.append(('반말 서술형', f'{part[:52]} — 존댓말로 쓰거나 개조식으로 끝낼 것'))
                    break
    for sent, side, np, nq in register_mix(mix_sents):
        warn.append(('말투 섞임',
                     f'{sent[:50]} — 이 문서는 존댓말 {np} · 반말 {nq} 이라 '
                     f'{side} 한 줄이 튄다'))

    # 4b. 제목 — 마크다운과 같은 규칙을 HTML 에도 건다.
    #     규칙(§1 개조식)은 진작 있었는데 이 경로에만 안 걸려 있었다. 그래서 값은
    #     전부 개조식인 아티팩트가 **제목만 서술 문장인 채로** 오류 0 을 받았다
    #     (2026-09-02 실측 — 검사기가 아니라 사람이 읽고서야 걸렸다).
    #     `<br>` 은 줄을 가른다 — 통째로 이어 붙이면 끝만 보게 되어 앞 줄의
    #     서술형이 빠진다: 「…잇는다<br>땅속 실그물」이 그 형태다.
    #     서술형 판정은 `is_narrative` 를 쓴다 — 위 값 슬롯과 같은 함수이고,
    #     인용 안 서술형을 값의 종결로 오인하지 않는다(「결론은 「…낮다」」).
    #     ★ 두 검사의 단위가 다르다. 서술형은 **줄마다**, 절단형·의문형은
    #     **제목 전체**를 놓고 본다. 명사구 하나가 두 줄로 접힌 것뿐인데 줄마다
    #     절단형을 재면 「흩어진 회사 자료를 잇는 / 땅속 실그물」의 앞 줄이
    #     조사 종결로 잡힌다. 거꾸로 서술형을 이어 붙여 재면 앞 줄이 통째로 빠진다.
    #     ★ `sentences`·`is_narrative` 에는 **꼬리를 떼기 전** 원문을 넘긴다.
    #     `drop_tail` 이 닫는 「」를 먼저 떼면 인용이 열린 채 남아 그 안의
    #     서술형이 제목의 종결이 된다 — 「「관찰한 사실은 LCT가 낸다」」가 그 형태다.
    for inner in re.findall(r'<h[1-6][^>]*>(.*?)</h[1-6]>', body, re.S):
        pieces = [x for x in (strip(p).replace('**', '')
                              for p in re.split(r'<br\s*/?>', inner)) if x]
        for piece in pieces:
            if is_example(piece):
                continue
            for sent in sentences(piece):
                if is_narrative(sent):
                    err.append(('제목 서술형', sent[:56]))
        whole = ' '.join(pieces)
        if not whole or is_example(whole) or all_quoted(whole):
            continue
        # 마크다운 경로와 **같은 글자로** 낸다 — 꼬리 괄호를 뗀 뒤의 제목을 보여
        # 준다. 안 맞추면 같은 제목의 같은 판정이 두 경로에서 다른 문장으로 나와
        # 대조가 안 된다(실측 대조에서 어긋난 23건이 전부 이 표기 차이였다).
        shown = drop_tail(whole)
        fe, fw = fragment(shown)
        if fe:
            err.append(('제목 명사형 위반', f'{shown[:50]} — {fe}'))
        elif fw and '의문형' in fw:
            err.append(('제목 명사형 위반', f'{shown[:50]} — {fw}'))
        elif fw:
            warn.append(('제목 형태 확인', f'{shown[:50]} — {fw}'))

    # 5. 진입점 — 있어야 하고, 그 한 줄도 개조식이어야 한다.
    #    `class="lede"` 를 요구하지 않는다 — 그러면 다른 템플릿의 진입점을 못 본다
    ledes = re.findall(r'<p[^>]*class="lede"[^>]*>(.*?)</p>', body, re.S)
    if '<h1' in body:
        if not ledes:
            after = body.split('</h1>', 1)[1] if '</h1>' in body else ''
            first = re.search(r'<p(?![a-zA-Z])[^>]*>(.*?)</p>', after, re.S)
            if not first or not strip(first.group(1)):
                err.append(('진입점 없음', '맨 앞에 「이 문서를 읽고 무엇을 하게 되나」 한 줄'))
            else:
                ledes = [first.group(1)]
    for lede in ledes:
        # ⛔ **절단형·의문형도 본다**(2026-09-18). 여기가 서술형만 보고 있어서
        #    진입점이 「무엇을 보나」(의문형)이거나 조사로 끝나도 HTML 은 통과시켰다.
        #    마크다운 경로는 진작 보고 있었다 — 제목 검사가 HTML 에만 빠져 있던
        #    2026-09-02 건과 **같은 모양**이고, 형식 짝 시험의 예외 사유에
        #    「다른 시험이 대조한다」고 **거짓으로 적어 두어** 가려져 있었다.
        t = drop_tail(strip(lede).replace('**', ''))
        for v in split_value(t)[0]:
            fe, fw = (None, None) if all_quoted(v) else fragment(drop_tail(v))
            if fe:
                err.append(('진입점 명사형 위반', f'{v[:48]} — {fe}'))
            elif fw and '의문형' in fw:
                err.append(('진입점 명사형 위반', f'{v[:48]} — {fw}'))
            elif fw:
                warn.append(('진입점 형태 확인', f'{v[:48]} — {fw}'))
        for chunk in re.split(r'(?<=\.)\s+', strip(lede)):
            c = chunk.strip()
            if c and NARRATIVE.search(c) and not NOT_NARRATIVE.search(c):
                err.append(('진입점 서술형', c[:58]))

    # 6. 반복 블록의 라벨 대조 — 같은 슬롯에 다른 말이 오는지
    cards = re.findall(r'<(?:article|section)[^>]*>(.*?)</(?:article|section)>', body, re.S)
    sets = [[strip(x) for x in re.findall(r'<dt[^>]*>(.*?)</dt>', c, re.S)] for c in cards]
    sets = [s for s in sets if s]
    if len(sets) >= 3:
        cnt = collections.Counter(x for s in sets for x in s)
        once = [k for k, v in cnt.items() if v == 1]
        if len(once) > len(sets) / 2:
            warn.append(('반복 블록 라벨 불일치',
                         f'{len(sets)}개 블록에서 1회용 라벨 {len(once)}종: {", ".join(once[:6])}'))

    # 7. 출처 없는 인용 블록 = 해설이다 — 인용 부호만 썼을 뿐 값과 같은 규칙을 받는다.
    #    ⛔ **마크다운 경로에만 있던 갈래다**(2026-09-18). 같은 문장을 `>` 로 쓰면
    #       잡히고 `<blockquote>` 로 쓰면 통과했다. 제목(09-02)·문단(09-04)·
    #       인라인 코드(09-07)에 이은 **네 번째 같은 모양**이라, 낱말을 하나씩
    #       옮기는 대신 `test_rule_parity_between_formats.py` 로 전 갈래를 대조한다.
    for inner in re.findall(r'<blockquote[^>]*>(.*?)</blockquote>', body, re.S | re.I):
        flat = ' '.join(strip(inner).split())
        if ATTRIB.search(flat):          # 남의 말 원문은 글자가 같아야 한다
            continue
        for chunk in re.split(r'(?<=다\.)\s+', flat):
            c = chunk.replace('**', '').strip()
            if c and NARRATIVE.search(c) and not NOT_NARRATIVE.search(c):
                warn.append(('해설을 인용 부호로 씀', f'{c[:52]} — 라벨:값으로 고칠 것'))

    # HTML 에는 머리말이 없다. 플래그만 받으면 **검사할 때마다 사람이 기억해야 하고**,
    # 기억해야 하는 구조는 실패한다 — `<meta name="form" content="prose">` 로 파일이
    # 자기 형식을 들고 있게 한다. 플래그가 오면 그쪽이 이긴다(그 자리에서 뒤집어 봄).
    err, warn = apply_form(err, warn, form or declared_form(raw))
    err, warn = apply_instruction_file(err, warn, path)
    err, warn = apply_selection(err, warn, rules) if rules else (err, warn)
    return err, warn, slots


